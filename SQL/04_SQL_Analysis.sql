-- =======================================================================
-- Project: Personal Expenses Dashboard
-- Purpose: Analysis queries for the EXPENSES table (Oracle 10g)
-- =======================================================================


-- 1. Overall expense summary
SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,
    SUM(AMOUNT) AS TOTAL_EXPENSES,
    ROUND(AVG(AMOUNT), 2) AS AVERAGE_EXPENSE,
    MIN(AMOUNT) AS MINIMUM_EXPENSE,
    MAX(AMOUNT) AS MAXIMUM_EXPENSE
FROM EXPENSES;


-- 2. Total spending by category
SELECT
    CATEGORY,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(AMOUNT) AS TOTAL_SPENDING,
    ROUND(AVG(AMOUNT), 2) AS AVERAGE_SPENDING
FROM EXPENSES
GROUP BY CATEGORY
ORDER BY TOTAL_SPENDING DESC;


-- 3. Total spending by payment method
SELECT
    PAYMENT_METHOD,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(AMOUNT) AS TOTAL_SPENDING,
    ROUND(AVG(AMOUNT), 2) AS AVERAGE_SPENDING
FROM EXPENSES
GROUP BY PAYMENT_METHOD
ORDER BY TOTAL_SPENDING DESC;


-- 4. Monthly spending trend
SELECT
    TO_CHAR(EXPENSE_DATE, 'YYYY-MM') AS EXPENSE_MONTH,
    COUNT(*) AS TRANSACTION_COUNT,
    SUM(AMOUNT) AS TOTAL_MONTHLY_SPENDING,
    ROUND(AVG(AMOUNT), 2) AS AVERAGE_MONTHLY_SPENDING
FROM EXPENSES
GROUP BY TO_CHAR(EXPENSE_DATE, 'YYYY-MM')
ORDER BY EXPENSE_MONTH;


-- 5. Top 5 highest individual expenses
SELECT *
FROM (
    SELECT
        EXPENSE_ID,
        EXPENSE_DATE,
        CATEGORY,
        DESCRIPTION,
        PAYMENT_METHOD,
        AMOUNT
    FROM EXPENSES
    ORDER BY AMOUNT DESC
)
WHERE ROWNUM <= 5;


-- 6. Top 5 lowest individual expenses
SELECT *
FROM (
    SELECT
        EXPENSE_ID,
        EXPENSE_DATE,
        CATEGORY,
        DESCRIPTION,
        PAYMENT_METHOD,
        AMOUNT
    FROM EXPENSES
    ORDER BY AMOUNT ASC
)
WHERE ROWNUM <= 5;


-- 7. Highest spending category
SELECT *
FROM (
    SELECT
        CATEGORY,
        SUM(AMOUNT) AS TOTAL_SPENDING
    FROM EXPENSES
    GROUP BY CATEGORY
    ORDER BY TOTAL_SPENDING DESC
)
WHERE ROWNUM = 1;


-- 8. Lowest spending category
SELECT *
FROM (
    SELECT
        CATEGORY,
        SUM(AMOUNT) AS TOTAL_SPENDING
    FROM EXPENSES
    GROUP BY CATEGORY
    ORDER BY TOTAL_SPENDING ASC
)
WHERE ROWNUM = 1;


-- 9. Most frequently used payment method
SELECT *
FROM (
    SELECT
        PAYMENT_METHOD,
        COUNT(*) AS TRANSACTION_COUNT
    FROM EXPENSES
    GROUP BY PAYMENT_METHOD
    ORDER BY TRANSACTION_COUNT DESC
)
WHERE ROWNUM = 1;


-- 10. Most expensive transaction
SELECT *
FROM (
    SELECT
        EXPENSE_ID,
        EXPENSE_DATE,
        CATEGORY,
        DESCRIPTION,
        PAYMENT_METHOD,
        AMOUNT
    FROM EXPENSES
    ORDER BY AMOUNT DESC
)
WHERE ROWNUM = 1;


-- 11. Spending by category and month
SELECT
    TO_CHAR(EXPENSE_DATE, 'YYYY-MM') AS EXPENSE_MONTH,
    CATEGORY,
    SUM(AMOUNT) AS TOTAL_SPENDING
FROM EXPENSES
GROUP BY TO_CHAR(EXPENSE_DATE, 'YYYY-MM'), CATEGORY
ORDER BY EXPENSE_MONTH, CATEGORY;


-- 12. Payment method spending percentage
SELECT
    PAYMENT_METHOD,
    SUM(AMOUNT) AS TOTAL_SPENDING,
    ROUND(
        (SUM(AMOUNT) / NULLIF((SELECT SUM(AMOUNT) FROM EXPENSES), 0)) * 100,
        2
    ) AS SPENDING_PERCENTAGE
FROM EXPENSES
GROUP BY PAYMENT_METHOD
ORDER BY TOTAL_SPENDING DESC;


-- 13. Category spending percentage
SELECT
    CATEGORY,
    SUM(AMOUNT) AS TOTAL_SPENDING,
    ROUND(
        (SUM(AMOUNT) / NULLIF((SELECT SUM(AMOUNT) FROM EXPENSES), 0)) * 100,
        2
    ) AS SPENDING_PERCENTAGE
FROM EXPENSES
GROUP BY CATEGORY
ORDER BY TOTAL_SPENDING DESC;


-- 14. Daily spending
SELECT
    EXPENSE_DATE,
    COUNT(*) AS NUMBER_OF_TRANSACTIONS,
    SUM(AMOUNT) AS TOTAL_DAILY_SPENDING
FROM EXPENSES
GROUP BY EXPENSE_DATE
ORDER BY EXPENSE_DATE;


-- 15. Highest spending day
SELECT *
FROM (
    SELECT
        EXPENSE_DATE,
        SUM(AMOUNT) AS TOTAL_DAILY_SPENDING
    FROM EXPENSES
    GROUP BY EXPENSE_DATE
    ORDER BY TOTAL_DAILY_SPENDING DESC
)
WHERE ROWNUM = 1;


-- 16. Monthly highest spending
SELECT *
FROM (
    SELECT
        TO_CHAR(EXPENSE_DATE, 'YYYY-MM') AS EXPENSE_MONTH,
        SUM(AMOUNT) AS TOTAL_MONTHLY_SPENDING
    FROM EXPENSES
    GROUP BY TO_CHAR(EXPENSE_DATE, 'YYYY-MM')
    ORDER BY TOTAL_MONTHLY_SPENDING DESC
)
WHERE ROWNUM = 1;


-- 17. Category transaction frequency
SELECT
    CATEGORY,
    COUNT(*) AS NUMBER_OF_TRANSACTIONS,
    ROUND(
        (COUNT(*) / NULLIF((SELECT COUNT(*) FROM EXPENSES), 0)) * 100,
        2
    ) AS TRANSACTION_PERCENTAGE
FROM EXPENSES
GROUP BY CATEGORY
ORDER BY NUMBER_OF_TRANSACTIONS DESC;


-- 18. Average transaction amount by payment method
SELECT
    PAYMENT_METHOD,
    ROUND(AVG(AMOUNT), 2) AS AVERAGE_TRANSACTION_AMOUNT
FROM EXPENSES
GROUP BY PAYMENT_METHOD
ORDER BY AVERAGE_TRANSACTION_AMOUNT DESC;


-- 19. Average transaction amount by category
SELECT
    CATEGORY,
    ROUND(AVG(AMOUNT), 2) AS AVERAGE_TRANSACTION_AMOUNT
FROM EXPENSES
GROUP BY CATEGORY
ORDER BY AVERAGE_TRANSACTION_AMOUNT DESC;


-- 20. Dashboard KPI query
SELECT
    SUM(AMOUNT) AS TOTAL_EXPENSES,
    COUNT(*) AS TOTAL_TRANSACTIONS,
    ROUND(AVG(AMOUNT), 2) AS AVERAGE_EXPENSE,
    MAX(AMOUNT) AS HIGHEST_EXPENSE,
    MIN(AMOUNT) AS LOWEST_EXPENSE
FROM EXPENSES;